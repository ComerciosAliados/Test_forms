function cmfRedesHTML(r){return (r||[]).map(function(x){var ic=x.i==='ig'?'ig.png':'web.png';return '<a href="'+x.u+'" target="_blank" rel="noopener noreferrer"><img src="https://storage.googleapis.com/web-cmf/comercios/'+ic+'" alt="enlace"></a>';}).join('');}
function renderComercios(){
  var grid=document.getElementById('brands-grid'); if(!grid) return;
  var html=COMERCIOS.map(function(c){
    var hid=c.def==='hid';
    var logo=c.logo?'<div class="brand-card-logo"><img src="'+c.logo+'" alt="'+c.n+'" loading="lazy"></div>':'';
    return '<div class="brand-card'+(hid?' oculto':'')+'" data-prov="'+(c.prov||'')+'" data-cat="'+(c.cat||'')+'" data-def="'+(c.def||'')+'">'
      +logo+'<div class="brand-card-name">'+c.n+'</div><div class="brand-card-tag">'+(c.tag||'')+'</div>'
      +'<div class="brand-card-addr">'+(c.addr||'—')+'</div><div class="brand-card-redes">'+cmfRedesHTML(c.redes)+'</div></div>';
  }).join('');
  var oc=COMERCIOS.filter(function(c){return c.def==='hid';}).length;
  html+='<div class="brand-card more" id="btn-mas-comercios" onclick="verTodosComercios()"><div class="brand-card-name">+'+oc+'</div><div class="brand-card-tag">socios más en toda Panamá</div></div>';
  grid.innerHTML=html;
  if(typeof cmfRender==='function') cmfRender();
}
document.addEventListener('DOMContentLoaded', renderComercios);
